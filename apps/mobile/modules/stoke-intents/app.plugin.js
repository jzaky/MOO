/**
 * Stoke "intents" config plugin (runs on `npx expo prebuild`):
 *
 * iOS     – compiles swift/StokeAppIntents.swift into the main app target:
 *           the "Log food in Stoke" App Intent (text parameter), a "Start a
 *           workout" intent and their App Shortcut phrases. Each intent opens
 *           the app through a deep link (stoke://log?text=…, stoke://workout/start).
 * Android – adds static launcher shortcuts (long-press the app icon) for the
 *           same deep links: res/xml/stoke_shortcuts.xml + MainActivity meta-data.
 *
 * No runtime JS; the deep links are resolved by src/app/+native-intent.tsx.
 */
const fs = require("fs");
const path = require("path");
const { AndroidConfig, IOSConfig, createRunOncePlugin, withAndroidManifest, withDangerousMod, withStringsXml, withXcodeProject } = require("expo/config-plugins");

const SWIFT_FILE = "StokeAppIntents.swift";
const SHORTCUTS_XML = "stoke_shortcuts";

const ANDROID_SHORTCUTS = [
  { id: "log_food", url: "stoke://log", short: "Log food", long: "Log food by voice or text" },
  { id: "start_workout", url: "stoke://workout/start", short: "Start workout", long: "Start or resume a workout" },
  { id: "weigh_in", url: "stoke://weigh-in", short: "Weigh-in", long: "Log your body weight" },
];

const unquote = (s) => (typeof s === "string" ? s.replace(/^"(.*)"$/, "$1") : s);

function projectNameOf(cfg) {
  return cfg.modRequest.projectName ?? IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
}

/** The main iOS app target (by name, so a watchOS app target is never picked by mistake). */
function mainAppTargetUuid(project, projectName) {
  const section = project.pbxNativeTargetSection();
  const uuid = Object.keys(section).find((key) => {
    const t = section[key];
    return !key.endsWith("_comment") && typeof t === "object" && unquote(t.name) === projectName && unquote(t.productType) === "com.apple.product-type.application";
  });
  if (!uuid) throw new Error(`[stoke-intents] Could not find the "${projectName}" app target in the Xcode project.`);
  return uuid;
}

const withAppIntents = (config) => {
  config = withDangerousMod(config, [
    "ios",
    async (cfg) => {
      const dest = path.join(cfg.modRequest.platformProjectRoot, projectNameOf(cfg), SWIFT_FILE);
      await fs.promises.mkdir(path.dirname(dest), { recursive: true });
      await fs.promises.copyFile(path.join(__dirname, "swift", SWIFT_FILE), dest);
      return cfg;
    },
  ]);
  config = withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = projectNameOf(cfg);
    const filepath = `${projectName}/${SWIFT_FILE}`;
    if (!project.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project, targetUuid: mainAppTargetUuid(project, projectName) });
    }
    return cfg;
  });
  return config;
};

const escapeXml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function shortcutsXml(pkg) {
  const items = ANDROID_SHORTCUTS.map(
    (s) => `  <shortcut
    android:shortcutId="${s.id}"
    android:enabled="true"
    android:icon="@mipmap/ic_launcher"
    android:shortcutShortLabel="@string/stoke_shortcut_${s.id}"
    android:shortcutLongLabel="@string/stoke_shortcut_${s.id}_long">
    <intent
      android:action="android.intent.action.VIEW"
      android:data="${escapeXml(s.url)}"
      android:targetPackage="${pkg}"
      android:targetClass="${pkg}.MainActivity" />
  </shortcut>`,
  ).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by modules/stoke-intents. Do not edit. -->\n<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">\n${items}\n</shortcuts>\n`;
}

const withAndroidShortcuts = (config) => {
  config = withAndroidManifest(config, (cfg) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    const meta = (activity["meta-data"] ?? []).filter((m) => m.$["android:name"] !== "android.app.shortcuts");
    meta.push({ $: { "android:name": "android.app.shortcuts", "android:resource": `@xml/${SHORTCUTS_XML}` } });
    activity["meta-data"] = meta;
    return cfg;
  });
  config = withStringsXml(config, (cfg) => {
    const items = ANDROID_SHORTCUTS.flatMap((s) => [
      AndroidConfig.Resources.buildResourceItem({ name: `stoke_shortcut_${s.id}`, value: s.short }),
      AndroidConfig.Resources.buildResourceItem({ name: `stoke_shortcut_${s.id}_long`, value: s.long }),
    ]);
    cfg.modResults = AndroidConfig.Strings.setStringItem(items, cfg.modResults);
    return cfg;
  });
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const pkg = AndroidConfig.Package.getPackage(cfg);
      if (!pkg) throw new Error("[stoke-intents] android.package is required for launcher shortcuts.");
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${SHORTCUTS_XML}.xml`), shortcutsXml(pkg));
      return cfg;
    },
  ]);
  return config;
};

const withStokeIntents = (config) => withAndroidShortcuts(withAppIntents(config));

module.exports = createRunOncePlugin(withStokeIntents, "stoke-intents", "1.0.0");
